void vgui_strcpy( char* dst, int dstLen, const char* src )
{
	ASSERT_AT( dst!=null, 941 );
	ASSERT_AT( dstLen>=0, 942 );
	ASSERT_AT( src!=null, 943 );

	int length = strlen( src ) + 1;
	if ( length > dstLen )
	{
		length = dstLen;
	}

	memcpy( dst, src, length - 1 );
	dst[length - 1] = 0;
}

