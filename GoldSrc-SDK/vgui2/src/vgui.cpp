bool PriorityQueueComp( const MessageItem_t& x, const MessageItem_t& y )
{
	if ( x._arrivalTime > y._arrivalTime )
	{
		return true;
	}
	else if ( x._arrivalTime < y._arrivalTime )
	{
		return false;
	}

	return ( x._messageID > y._messageID );
}

