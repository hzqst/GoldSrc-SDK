void CVGui::RunFrame()
{
	vgui2::g_pSurface->RunFrame();
	vgui2::g_pSystem->RunFrame();

	int cursorX;
	int cursorY;
	vgui2::g_pInput->GetCursorPos( cursorX, cursorY );
	vgui2::g_pInput->UpdateMouseFocus( cursorX, cursorY );
	vgui2::g_pInput->RunFrame();

	DispatchMessages();

	int time = vgui2::g_pSystem->GetTimeMillis();
	for ( int i = m_TickSignalVec.Count() - 1; i >= 0; --i )
	{
		Tick_t* tick = m_TickSignalVec[i];
		if ( !tick->panel )
		{
			m_TickSignalVec.Remove( i );
			delete tick;
			continue;
		}

		if ( tick->interval != 0 )
		{
			if ( time < tick->nexttick )
			{
				continue;
			}

			tick->nexttick = time + tick->interval;
		}

		PostMessage( tick->panel, new KeyValues( "Tick" ), 0, 0.0f );
	}

	vgui2::VPANEL embedded = vgui2::g_pSurface->GetEmbeddedPanel();
	vgui2::g_pSurface->SolveTraverse( embedded, false );
	vgui2::g_pSurface->ApplyChanges();
}

//-----------------------------------------------------------------------------
// Purpose: 
//-----------------------------------------------------------------------------
void CVGui::ShutdownMessage( unsigned int shutdownID )
{
	vgui2::VPanel* embedded = (vgui2::VPanel*)vgui2::g_pSurface->GetEmbeddedPanel();

	for ( int i = 0; i < embedded->GetChildCount(); ++i )
	{
		KeyValues* params = new KeyValues( "ShutdownRequest", "id", shutdownID );
		vgui2::g_pIVgui->PostMessage( (vgui2::VPANEL)embedded->GetChild( i ), params, 0, 0.0f );
	}

	KeyValues* params = new KeyValues( "ShutdownRequest", "id", shutdownID );
	vgui2::g_pIVgui->PostMessage( (vgui2::VPANEL)embedded, params, 0, 0.0f );
}

