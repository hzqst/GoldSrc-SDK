//-----------------------------------------------------------------------------
// Purpose: Adds the panel to a tick signal list, so the panel receives a message every frame
// Input  : *panel - 
//-----------------------------------------------------------------------------
void CVGui::AddTickSignal( vgui2::VPANEL panel, int intervalMilliseconds )
{
	// See if it's already in list
	int count = m_TickSignalVec.Count();
	for ( int i = 0; i < count; ++i )
	{
		Tick_t* existing = m_TickSignalVec[i];
		if ( existing->panel == panel )
		{
			existing->interval = intervalMilliseconds;
			existing->nexttick = existing->interval + vgui2::g_pSystem->GetTimeMillis();
			return;
		}
	}

	Tick_t* tick = new Tick_t;
	tick->panel = panel;
	tick->interval = intervalMilliseconds;
	tick->nexttick = tick->interval + vgui2::g_pSystem->GetTimeMillis();

	vgui2::VPanel* vp = (vgui2::VPanel*)panel;
	const char* panelName = vp->Client()->GetName();
	if ( panelName[0] )
	{
		panelName = vp->Client()->GetName();
	}
	else
	{
		panelName = vp->Client()->GetClassName();
	}

	strncpy( tick->panelname, panelName, sizeof( tick->panelname ) );
	m_TickSignalVec.AddToTail( tick );
}

void CVGui::PostMessage( vgui2::VPANEL target, KeyValues* params, vgui2::VPANEL from, float delaySeconds )
{
	if ( !target )
	{
		if ( params )
		{
			params->deleteThis();
		}
		return;
	}

	MessageItem_t message;
	message._messageTo = vgui2::g_pIVgui->PanelToHandle( target );
	message._params = params;
	ASSERT_AT( params->GetName(), 776 );
	message._from = vgui2::g_pIVgui->PanelToHandle( from );
	message._arrivalTime = 0.0f;
	message._messageID = m_iCurrentMessageID++;

	/* message debug code
	//if ( stricmp(messageItem._params->GetName(),"CursorMoved") && stricmp(messageItem._params->GetName(),"KeyFocusTicked"))
	{
		ivgui()->DPrintf2( "posting( %s -- %i )\n", messageItem._params->GetName(), messageItem._messageID );
	}
	*/

	// add the message to the correct message queue
	if ( delaySeconds > 0.0f )
	{
		message._arrivalTime = vgui2::g_pSystem->GetTimeMillis() + delaySeconds * 1000.0f;
		m_DelayedMessageQueue.Insert( message );
	}
	else if ( m_InDispatcher )
	{
		m_SecondaryQueue.AddToTail( message );
	}
	else
	{
		m_MessageQueue.AddToTail( message );
	}
}

void CVGui::DestroyContext( vgui2::HContext context )
{
	ASSERT_AT( context != DEFAULT_VGUI_CONTEXT, 319 );

	if ( m_hContext == context )
	{
		ActivateContext( DEFAULT_VGUI_CONTEXT );
	}

	vgui2::g_pInput->DestroyInputContext( m_Contexts[(unsigned short)context].m_hInputContext );
	m_Contexts.Remove( (unsigned short)context );
}

void CVGui::ActivateContext( vgui2::HContext context )
{
#pragma warning( push )
#pragma warning( disable : 4244 )
	ASSERT_AT( (context == DEFAULT_VGUI_CONTEXT) || m_Contexts.IsValidIndex(context), 371 );
#pragma warning( pop )

	if ( m_hContext == context )
	{
		return;
	}

	DispatchMessages();
	m_hContext = context;

	if ( context == DEFAULT_VGUI_CONTEXT )
	{
		vgui2::g_pInput->ActivateInputContext( m_DefaultContext.m_hInputContext );
	}
	else
	{
		vgui2::g_pInput->ActivateInputContext( m_Contexts[(unsigned short)context].m_hInputContext );
		vgui2::g_pInput->RunFrame();
	}
}

