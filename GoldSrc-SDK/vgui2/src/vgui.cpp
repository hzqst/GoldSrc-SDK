vgui2::VPANEL CVGui::AllocPanel()
{
	vgui2::VPanel* panel = new vgui2::VPanel;
	PanelCreated( panel );
	return (vgui2::VPANEL)panel;
}

vgui2::HPanel CVGui::PanelToHandle( vgui2::VPANEL panel )
{
	if ( panel )
	{
		unsigned short listEntry = ( (vgui2::VPanel*)panel )->GetListEntry();
		return ( (unsigned int)listEntry << 16 ) + m_PanelList[listEntry].m_iSerialNumber;
	}

	return INVALID_VGUI_PANEL;
}

vgui2::VPANEL CVGui::HandleToPanel( vgui2::HPanel index )
{
	if ( index == INVALID_VGUI_PANEL )
	{
		return 0;
	}

	unsigned short listEntry = (unsigned short)( index >> 16 );
	if ( m_PanelList.IsValidIndex( listEntry ) && m_PanelList[listEntry].m_iSerialNumber == (unsigned short)index )
	{
		return m_PanelList[listEntry].m_pPanel;
	}

	return 0;
}

//-----------------------------------------------------------------------------
// Purpose: Called whenever a panel is constructed
//-----------------------------------------------------------------------------
void CVGui::PanelCreated( vgui2::VPanel* panel )
{
	vgui2::SerialPanel_t slot;
	slot.m_iSerialNumber = m_iNextSerialNumber++;
	slot.m_pPanel = (vgui2::VPANEL)panel;

	unsigned short listEntry = m_PanelList.AddToTail();
	m_PanelList[listEntry] = slot;
	panel->SetListEntry( listEntry );
	vgui2::g_pSurface->AddPanel( (vgui2::VPANEL)panel );
}

//-----------------------------------------------------------------------------
// Purpose: instantly stops the app from pointing to the focus'd object
//			used when an object is being deleted
//-----------------------------------------------------------------------------
void CVGui::PanelDeleted( vgui2::VPanel* focus )
{
	ASSERT_AT( focus, 564 );
	vgui2::g_pSurface->ReleasePanel( (vgui2::VPANEL)focus );
	vgui2::g_pInput->PanelDeleted( (vgui2::VPANEL)focus );

	unsigned short index = focus->GetListEntry();
	ASSERT_AT( m_PanelList.IsValidIndex(index), 571 );
	if ( m_PanelList.IsValidIndex( index ) )
	{
		m_PanelList.Remove( index );
	}

	focus->SetListEntry( m_PanelList.InvalidIndex() );
	// remove from tick signal dar
	RemoveTickSignal( (vgui2::VPANEL)focus );
}

//-----------------------------------------------------------------------------
// Purpose: 
// Input  : panel - 
//-----------------------------------------------------------------------------
void CVGui::RemoveTickSignal( vgui2::VPANEL panel )
{
	for ( int i = 0; i < m_TickSignalVec.Count(); i++ )
	{
		Tick_t* tick = m_TickSignalVec[i];
		if ( tick->panel == panel )
		{
			m_TickSignalVec.Remove( i );
			delete tick;
			return;
		}
	}
}

void CVGui::DPrintf( const char* format, ... )
{
	char buf[MAX_DEBUG_MESSAGE];
	va_list argptr;

	va_start( argptr, format );
	vsprintf( buf, format, argptr );
	va_end( argptr );
#ifdef _WIN32
	OutputDebugStringA( buf );
#else
	fputs( buf, stderr );
#endif
}

void CVGui::DPrintf2( const char* format, ... )
{
	char buf[MAX_DEBUG_MESSAGE];
	static int ctr = 0;
	va_list argptr;

	sprintf( buf, "%d:", ctr++ );
	va_start( argptr, format );
	vsprintf( &buf[strlen( buf )], format, argptr );
	va_end( argptr );
#ifdef _WIN32
	OutputDebugStringA( buf );
#else
	fputs( buf, stderr );
#endif
}

