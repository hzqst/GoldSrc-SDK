void CVGui::SpewAllActivePanelNames()
{
	for ( int i = m_PanelList.Head(); i != m_PanelList.InvalidIndex(); i = m_PanelList.Next( (unsigned short)i ) )
	{
		vgui2::VPANEL panel = m_PanelList[(unsigned short)i].m_pPanel;
		vgui2::g_pIVgui->DPrintf2( "\tpanel '%s' of type '%s' leaked\n",
				vgui2::g_pIPanel->GetName( panel ), ( (vgui2::VPanel*)panel )->GetClassName() );
	}
}

