#pragma once

#include <cstddef>
#include "../color.h"

class IFileSystem;
class CUtlBuffer;

typedef unsigned long long uint64;

class KeyValues
{
public:
	enum types_t
	{
		TYPE_NONE = 0,
		TYPE_STRING,
		TYPE_INT,
		TYPE_FLOAT,
		TYPE_PTR,
		TYPE_WSTRING,
		TYPE_COLOR,
		TYPE_UINT64
	};

	KeyValues( const char* name );
	// Quick setup constructors
	KeyValues( const char* name, const char* firstKey, const char* firstValue );
	KeyValues( const char* name, const char* firstKey, const wchar_t* firstValue );
	KeyValues( const char* name, const char* firstKey, int firstValue );
	KeyValues( const char* name, const char* firstKey, const char* firstValue, const char* secondKey,
		const char* secondValue );
	KeyValues( const char* name, const char* firstKey, int firstValue, const char* secondKey, int secondValue );

	virtual const char* GetName() const;
	virtual int GetNameSymbol() const;

	// file access
	virtual bool LoadFromFile( IFileSystem* fileSystem, const char* filename, const char* pathID );
	virtual bool SaveToFile( IFileSystem* fileSystem, const char* filename, const char* pathID );

	virtual KeyValues* FindKey( const char* name, bool create );
	virtual KeyValues* FindKey( int symbol ) const;
	virtual KeyValues* CreateNewKey(); // creates a new key, with an autogenerated name.  name is guaranteed to be an integer, of value 1 higher than the highest other integer key name
	void AddSubKey( KeyValues* key );
	virtual void RemoveSubKey( KeyValues* key );
	virtual KeyValues* GetFirstSubKey(); // returns the first subkey in the list
	virtual KeyValues* GetNextKey(); // returns the next subkey
	void SetNextKey( KeyValues* key );

	// data access
	virtual int GetInt( const char* name, int defaultValue );
	uint64 GetUint64( const char* name, uint64 defaultValue );
	virtual float GetFloat( const char* name, float defaultValue );
	virtual const char* GetString( const char* name, const char* defaultValue );
	virtual const wchar_t* GetWString( const char* name, const wchar_t* defaultValue );
	virtual void* GetPtr( const char* name, void* defaultValue );
	Color GetColor( const char* name );
	virtual bool IsEmpty( const char* name );

	virtual void SetWString( const char* name, const wchar_t* value );
	virtual void SetString( const char* name, const char* value );
	virtual void SetInt( const char* name, int value );
	void SetUint64( const char* name, uint64 value );
	virtual void SetFloat( const char* name, float value );
	virtual void SetPtr( const char* name, void* value );
	void SetColor( const char* name, Color value );

	void* operator new( std::size_t size );
	void* operator new( std::size_t size, int blockType, const char* filename, int line );
	void operator delete( void* memory );
	void operator delete( void* memory, int blockType, const char* filename, int line );

	virtual KeyValues* MakeCopy() const;
	virtual void Clear();
	virtual types_t GetDataType( const char* name );
	virtual void deleteThis();

	void LoadFromBuffer( const char* buffer );

private:
	KeyValues( KeyValues& other ); // prevent copy constructor being used
	~KeyValues();

	void RecursiveSaveToFile( IFileSystem* fileSystem, CUtlBuffer& buffer, int indent );
	void WriteConvertedString( CUtlBuffer& buffer, const char* text );
	void RecursiveLoadFromBuffer( char** buffer );
	void Init( const char* name );
	void FreeAllocatedValue();
	void AllocateValueBlock( int size );

	int m_iKeyName;

	// we don't delete these
	union
	{
		int				m_iValue;
		float			m_flValue;
		void*			m_pValue;
		char*			m_sValue;
		unsigned char	m_Color[4];
	};

	unsigned short	m_iDataType;
	short			m_iAllocationSize;

	KeyValues*		m_pPeer; // pointer to next key in list
	KeyValues*		m_pSub;
};
